@app.post("/api/collections/{name}/documents/batch")
def batch_insert(name: str, req: BatchDocumentInsertRequest):
    if name not in collections:
        raise HTTPException(status_code=404, detail="Collection not found")
    coll = collections[name]

    inserted_ids = []
    base_id = int(time.time() * 1000) % 10000000
    for idx, doc in enumerate(req.documents):
        doc_id = doc.id if doc.id is not None else (base_id + idx)
        vec = doc.vector if doc.vector else embedder.embed_text(doc.title + " " + doc.content)
        meta = {
            "title": doc.title,
            "content": doc.content,
            "category": doc.category
        }
        coll.insert(doc_id, vec, meta)
        inserted_ids.append(doc_id)

    return {"inserted_count": len(inserted_ids), "ids": inserted_ids}

@app.post("/api/collections/{name}/search")
def search(name: str, req: SearchRequest):
    if name not in collections:
        raise HTTPException(status_code=404, detail="Collection not found")
    coll = collections[name]

    if req.vector:
        query_vec = req.vector
    elif req.query:
        query_vec = embedder.embed_text(req.query)
    else:
        raise HTTPException(status_code=400, detail="Must provide query text or vector")

    alpha = req.hybrid_alpha if req.hybrid_alpha is not None else 0.5
    res = coll.search(
        query_vec=query_vec,
        query_text=req.query,
        k=req.top_k,
        ef=req.ef_search,
        filter_category=req.category,
        hybrid_alpha=alpha,
        search_mode=req.search_mode
    )
    return res

