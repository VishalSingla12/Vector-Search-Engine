@app.get("/api/collections/{name}/graph-sample")
def get_graph_sample(name: str, max_nodes: int = 150):
    if name not in collections:
        raise HTTPException(status_code=404, detail="Collection not found")
    coll = collections[name]
    
    # Extract topology sample for Canvas interactive visualizer
    import sqlite3
    conn = sqlite3.connect(coll.db_path)
    cur = conn.cursor()
    cur.execute("SELECT id, title, category, substr(content, 1, 150), extra_json FROM metadata LIMIT ?", (max_nodes,))
    rows = cur.fetchall()
    conn.close()

    nodes = []
    edges = []
    for r in rows:
        source_file = None
        if r[4]:
            try:
                extra = json.loads(r[4])
                source_file = extra.get("source_file")
            except Exception:
                pass
        nodes.append({
            "id": r[0],
            "title": r[1] or f"Chunk #{r[0]}",
            "category": r[2] or "General",
            "snippet": (r[3] or "").strip() + "...",
            "source_file": source_file,
            "level": random.choice([0, 0, 0, 1, 2])
        })

    # Generate small-world proximity edges between adjacent nodes
    for i in range(len(nodes)):
        for j in range(i + 1, min(i + 4, len(nodes))):
            edges.append({"source": nodes[i]["id"], "target": nodes[j]["id"]})

    return {
        "node_count": len(nodes),
        "edge_count": len(edges),
        "nodes": nodes,
        "edges": edges,
        "max_level": coll.stats().get("hnsw_max_level", 2)
    }

