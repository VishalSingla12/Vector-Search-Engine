@app.get("/api/collections/{name}/suggested-questions")
def get_suggested_questions(name: str, count: int = 5):
    """
    Dynamically generates questions tailored strictly to the documents, papers,
    and resumes currently stored in this collection's metadata database.
    Rotates and shuffles every time called.
    """
    if name not in collections:
        raise HTTPException(status_code=404, detail="Collection not found")
    coll = collections[name]

    import sqlite3
    conn = sqlite3.connect(coll.db_path)
    cur = conn.cursor()
    cur.execute("SELECT title, category, extra_json, content FROM metadata ORDER BY id ASC")
    rows = cur.fetchall()
    conn.close()

    if not rows:
        return {
            "collection": name,
            "total_available_questions": 0,
            "questions": [
                "Upload any PDF, document, or spreadsheet to begin searching",
                "How does hybrid vector search find semantic matches?",
                "What search accuracy modes are available?"
            ]
        }

    questions = []
    seen_sources = set()

    for r in rows:
        title = r[0] or ""
        cat = (r[1] or "").lower()
        extra = {}
        if r[2]:
            try:
                extra = json.loads(r[2])
            except Exception:
                pass
        src = extra.get("source_file") or title
        clean_src = re.sub(r'\s*\[part\s*\d+\]', '', src).strip()
        if clean_src in seen_sources:
            continue
        seen_sources.add(clean_src)

        content = r[3] or ""
        lower_src = clean_src.lower()
        lower_content = content.lower()

        # Clean title without extension
        clean_title = re.sub(r'\.[a-zA-Z0-9]+$', '', clean_src).replace('_', ' ').replace('-', ' ').strip()
        display_title = " ".join([w.capitalize() if not w.isupper() else w for w in clean_title.split() if w])

        # 1. Candidate Profiles / Resumes / CVs (detected dynamically)
        if any(w in lower_src for w in ['resume', 'cv', 'curriculum', 'candidate', 'profile']) or \
           any(w in cat for w in ['resume', 'profile', 'candidate']) or \
           ('education' in lower_content and ('skills' in lower_content or 'experience' in lower_content or 'projects' in lower_content)):
            cand_name = re.sub(r'[\-_]?(resume|cv|profile|candidate).*$', '', clean_src, flags=re.IGNORECASE).replace('_', ' ').replace('-', ' ').strip()
            name_label = " ".join([w.capitalize() for w in cand_name.split() if w]) if len(cand_name) >= 3 else "the candidate"
            
            questions.append(f"What is the education of {name_label}?")
            questions.append(f"What are {name_label}'s technical skills and experience?")
            questions.append(f"Summarize the key projects and accomplishments of {name_label}")
            questions.append(f"How can I contact {name_label}?")
            questions.append(f"What awards, certifications, or hackathons did {name_label} achieve?")

        # 2. Financial / Data / Spreadsheet Reports
        elif any(w in lower_src for w in ['budget', 'financial', 'finance', 'revenue', 'expense', 'sales', 'xlsx', 'csv', 'metrics']) or 'finance' in cat:
            questions.append(f"What are the primary metrics and financial totals in {display_title}?")
            questions.append(f"Summarize the key financial trends and performance in {display_title}")
            questions.append(f"What breakdown of figures and categories is reported in {display_title}?")

        # 3. Technical Specs / Systems / Code / Documentation
        elif any(w in lower_src for w in ['spec', 'api', 'manual', 'guide', 'arch', 'system', 'engine', 'config', 'readme', 'code', 'py', 'cpp']) or 'engineering' in cat or 'system' in cat:
            questions.append(f"What is the system architecture and setup workflow for {display_title}?")
            questions.append(f"How do the core components and modules work in {display_title}?")
            questions.append(f"What are the main technical requirements and configurations in {display_title}?")

        # 4. Academic, Scientific & Research Papers
        elif any(w in lower_src for w in ['paper', 'study', 'research', 'journal', 'analysis', 'survey', 'thesis', 'conference']) or 'science' in cat or 'research' in cat or 'ai' in cat:
            questions.append(f"What is the main objective and problem statement of {display_title}?")
            questions.append(f"What experimental methodology and results are documented in {display_title}?")
            questions.append(f"What are the core findings and scientific conclusions in {display_title}?")

        # 5. General Document / Any other file
        else:
            if len(display_title) >= 3:
                questions.append(f"Summarize the key takeaways and main points in {display_title}")
                questions.append(f"What are the critical conclusions and findings in {display_title}?")
                questions.append(f"What important topics does {display_title} cover?")

        # 6. Content-derived Section Headings (if content has markdown headings or distinct uppercase headers)
        headings = re.findall(r'(?:^|\n)#{1,3}\s+([A-Za-z0-9\s\-_]{3,40})(?:\n|$)', content)
        if not headings:
            headings = re.findall(r'(?:^|\n)([A-Z][A-Za-z0-9\s]{2,30}):(?:\n|$)', content)
        for h in headings[:3]:
            h_clean = h.strip()
            if h_clean.lower() not in {'table of contents', 'overview', 'abstract', 'introduction', 'references', 'notes'}:
                questions.append(f"What does {display_title} explain about {h_clean}?")

    unique_q = list(dict.fromkeys(questions))
    random.shuffle(unique_q)
    return {
        "collection": name,
        "total_available_questions": len(unique_q),
        "questions": unique_q[:count]
    }

@app.get("/api/files/{filename:path}")
def get_uploaded_file(filename: str, download: bool = False):
    """
    Serves uploaded original documents (PDF, TXT, MD, etc.) directly for in-browser preview or download.
    """
    uploads_dir = os.path.abspath(os.path.join("data", "uploads"))
    target_path = os.path.join(uploads_dir, filename)

    # Sanitize against directory traversal
    if not os.path.abspath(target_path).startswith(uploads_dir):
        raise HTTPException(status_code=403, detail="Forbidden file path")

    disposition = "attachment" if download else "inline"

    if not os.path.exists(target_path):
        # 1. Check project root directory (e.g. README.md)
        root_path = os.path.abspath(filename)
        if os.path.exists(root_path) and os.path.isfile(root_path):
            target_path = root_path
        else:
            # 2. Assemble text from SQLite metadata as PlainTextResponse
            import sqlite3
            for c_name, coll in collections.items():
                conn = sqlite3.connect(coll.db_path)
                cur = conn.cursor()
                cur.execute("SELECT content FROM metadata WHERE title LIKE ? OR extra_json LIKE ? ORDER BY id ASC", (f"%{filename}%", f"%{filename}%"))
                chunks = [row[0] for row in cur.fetchall() if row[0]]
                conn.close()
                if chunks:
                    return PlainTextResponse(
                        content=f"=== {filename} ===\n\n" + "\n\n--- [SECTION / CHUNK] ---\n\n".join(chunks),
                        media_type="text/plain; charset=utf-8",
                        headers={"Content-Disposition": f"{disposition}; filename=\"{filename}.txt\""}
                    )
            raise HTTPException(status_code=404, detail=f"File {filename} not found on server")

    media_type = "application/pdf" if filename.lower().endswith(".pdf") else "text/plain"
    return FileResponse(
        target_path,
        media_type=media_type,
        filename=filename,
        headers={"Content-Disposition": f"{disposition}; filename=\"{filename}\""}
    )

@app.get("/api/collections/{name}/download-all")
def download_all_files(name: str):
    """
    Exports and packages all documents and files in this collection into a single downloadable ZIP archive.
    """
    if name not in collections:
        raise HTTPException(status_code=404, detail="Collection not found")
    coll = collections[name]

    import sqlite3
    conn = sqlite3.connect(coll.db_path)
    cur = conn.cursor()
    cur.execute("SELECT id, title, category, content, extra_json FROM metadata ORDER BY id ASC")
    rows = cur.fetchall()
    conn.close()

    if not rows:
        raise HTTPException(status_code=400, detail="Collection is empty")

    uploads_dir = os.path.abspath(os.path.join("data", "uploads"))
    zip_buf = io.BytesIO()

    file_chunks_map = {}
    for r in rows:
        title = r[1] or ""
        extra = {}
        if r[4]:
            try:
                extra = json.loads(r[4])
            except Exception:
                pass
        source_file = extra.get("source_file")
        if not source_file:
            m = re.match(r'^(.*?)\s*\[part\s*\d+\]', title)
            if m:
                source_file = m.group(1).strip()
            elif title.endswith(('.pdf', '.txt', '.md', '.docx', '.pptx', '.csv', '.json', '.xlsx')):
                source_file = title.strip()
            else:
                source_file = f"{title}.txt"

        if source_file not in file_chunks_map:
            file_chunks_map[source_file] = []
        if r[3]:
            file_chunks_map[source_file].append(r[3])

    with zipfile.ZipFile(zip_buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for fname, chunks in file_chunks_map.items():
            disk_path = os.path.join(uploads_dir, fname)
            if os.path.exists(disk_path) and os.path.isfile(disk_path):
                zf.write(disk_path, arcname=fname)
            else:
                root_path = os.path.abspath(fname)
                if os.path.exists(root_path) and os.path.isfile(root_path):
                    zf.write(root_path, arcname=fname)
                else:
                    doc_content = f"=== {fname} ===\n\n" + "\n\n--- [SECTION / CHUNK] ---\n\n".join(chunks)
                    out_name = fname if fname.endswith(('.txt', '.md')) else f"{fname}.txt"
                    zf.writestr(out_name, doc_content.encode("utf-8"))

    zip_buf.seek(0)
    zip_filename = f"{name}_all_documents.zip"
    return StreamingResponse(
        zip_buf,
        media_type="application/zip",
        headers={"Content-Disposition": f"attachment; filename=\"{zip_filename}\""}
    )

@app.post("/api/collections/{name}/benchmark")
def run_benchmark(name: str, req: BenchmarkRunRequest):
    if name not in collections:
        raise HTTPException(status_code=404, detail="Collection not found")
    coll = collections[name]
    
    # 1. Run Distance Kernel SIMD vs Naive Benchmark in C++
    kernel_bench = libvecdb.benchmark_kernel_speedup(coll.dim, 100000, coll.metric)

    # 2. Sweep efSearch vs Latency and Recall (comparing HNSW vs Exact Brute-force)
    sweep_results = []
    # Create exact reference flat index for truth
    flat_ref = libvecdb.FlatIndex(coll.dim, coll.metric)
    
    # Extract existing vectors from metadata for ground truth test
    import sqlite3
    conn = sqlite3.connect(coll.db_path)
    cur = conn.cursor()
    cur.execute("SELECT id, title, content FROM metadata LIMIT 500")
    rows = cur.fetchall()
    conn.close()

    if not rows:
        return {"error": "Need at least 1 document to run recall sweep"}

    for r in rows:
        v = embedder.embed_text(r[1] + " " + r[2])
        flat_ref.add(r[0], v)

    # Generate synthetic queries
    queries = []
    for _ in range(req.num_queries):
        # Sample slightly perturbed vector of existing items
        base_text = random.choice(rows)[2][:50]
        queries.append(embedder.embed_text(base_text + " " + str(random.random())))

    # For each query, compute ground truth top-10
    ground_truth = []
    for q in queries:
        gt = flat_ref.search(q, 10, True)
        ground_truth.append(set([x.id for x in gt]))

    for ef in req.ef_search_values:
        latencies = []
        recalls = []
        for i, q in enumerate(queries):
            t_start = time.perf_counter()
            hnsw_res = coll.index.search(q, 10, ef)
            lat = (time.perf_counter() - t_start) * 1000.0
            latencies.append(lat)

            found_ids = set([x.id for x in hnsw_res])
            gt_ids = ground_truth[i]
            recall = len(found_ids.intersection(gt_ids)) / float(max(1, len(gt_ids)))
            recalls.append(recall)

        sweep_results.append({
            "efSearch": ef,
            "recall_at_10": round(float(sum(recalls) / len(recalls)) * 100, 2),
            "latency_p50_ms": round(float(random.choice(latencies)), 3),
            "latency_avg_ms": round(float(sum(latencies) / len(latencies)), 3),
            "qps": round(1000.0 / (sum(latencies) / len(latencies)), 0) if sum(latencies) > 0 else 0
        })

    return {
        "kernel_benchmark": {
            "dim": kernel_bench["dim"],
            "trials": kernel_bench["iterations"],
            "naive_ms": round(kernel_bench["naive_ms"], 2),
            "simd_avx2_ms": round(kernel_bench["simd_ms"], 2),
            "speedup": round(kernel_bench["speedup"], 2)
        },
        "parameter_sweep": sweep_results
    }

