class CreateCollectionRequest(BaseModel):
    name: str = Field(..., example="wikipedia_articles")
    dimension: int = Field(default=384, example=384)
    index_type: str = Field(default="hnsw", example="hnsw")
    metric: str = Field(default="cosine", example="cosine")

class DocumentInsertRequest(BaseModel):
    id: Optional[int] = None
    title: str = Field(..., example="Quantum Computing Fundamentals")
    content: str = Field(..., example="Quantum computing is a rapidly-emerging technology...")
    category: str = Field(default="Science", example="Science")
    vector: Optional[List[float]] = None

class BatchDocumentInsertRequest(BaseModel):
    documents: List[DocumentInsertRequest]

class SearchRequest(BaseModel):
    query: Optional[str] = None
    vector: Optional[List[float]] = None
    top_k: int = Field(default=10, ge=1, le=100)
    ef_search: int = Field(default=64, ge=1, le=512)
    category: Optional[str] = None
    hybrid_alpha: Optional[float] = Field(default=0.5, ge=0.0, le=1.0)
    search_mode: Optional[str] = None

class BenchmarkRunRequest(BaseModel):
    num_queries: int = Field(default=200, ge=5, le=1000)
    ef_search_values: List[int] = Field(default=[16, 32, 64, 128, 256])



