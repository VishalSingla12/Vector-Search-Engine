@app.get("/api/collections/{name}/files")
def list_collection_files(name: str):
    if name not in collections:
        raise HTTPException(status_code=404, detail="Collection not found")
    coll = collections[name]
    import sqlite3
    conn = sqlite3.connect(coll.db_path)
    cur = conn.cursor()
    cur.execute("SELECT id, title, category, created_at, extra_json, substr(content, 1, 150), length(content) FROM metadata ORDER BY id DESC")
    rows = cur.fetchall()
    conn.close()

    uploads_dir = os.path.abspath(os.path.join("data", "uploads"))
    files_map = {}
    for r in rows:
        source_file = None
        if r[4]:
            try:
                extra = json.loads(r[4])
                source_file = extra.get("source_file")
            except Exception:
                pass
        if not source_file:
            m = re.match(r'^(.*?)\s*\[part\s*\d+\]', r[1] or "")
            if m:
                source_file = m.group(1).strip()
            elif (r[1] or "").endswith(('.pdf', '.txt', '.md', '.docx', '.pptx', '.csv', '.json', '.xlsx', '.py', '.cpp', '.h', '.log')):
                source_file = (r[1] or "").strip()
            else:
                source_file = r[1] or f"doc_{r[0]}"

        char_len = r[6] if len(r) > 6 and r[6] else len(r[5] or "")

        if source_file not in files_map:
            # Check disk file size if exists
            disk_path = os.path.join(uploads_dir, source_file)
            fsize = None
            if os.path.exists(disk_path):
                fsize = os.path.getsize(disk_path)
            elif os.path.exists(os.path.abspath(source_file)) and os.path.isfile(os.path.abspath(source_file)):
                fsize = os.path.getsize(os.path.abspath(source_file))

            files_map[source_file] = {
                "filename": source_file,
                "first_id": r[0],
                "chunk_ids": [r[0]],
                "title": r[1],
                "category": r[2] or "document",
                "created_at": r[3],
                "filesize": fsize,
                "total_chars": char_len,
                "snippet": (r[5] or "") + "...",
                "file_url": f"/api/files/{source_file}"
            }
        else:
            files_map[source_file]["chunk_ids"].append(r[0])
            files_map[source_file]["total_chars"] += char_len

    result = list(files_map.values())
    for f in result:
        f["chunk_count"] = len(f["chunk_ids"])
        # If filesize not directly on disk, compute accurate text byte size
        if not f["filesize"]:
            f["filesize"] = max(512, int(f.get("total_chars", 1000) * 1.05))
    return result

